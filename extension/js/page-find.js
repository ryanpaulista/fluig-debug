// js/page-find.js — Expressoes de pagina: localizar campo, focar elemento, coletar linha
// Script classico (escopo global compartilhado); ordem de carga definida em panel.html.

// ---------------------------------------------------------------------------
// Localizar campo (usado por ler e por setar)
// ---------------------------------------------------------------------------

// Localiza um campo pelo nome digitado, tratando "_" e "___N", e retorna todas
// as ocorrencias reais no DOM. Cada match traz `exact` (name/id igual ao
// digitado) para o setar poder mirar uma ocorrencia especifica.
function buildFindExpr(typed) {
  var typedLit = JSON.stringify(typed);
  return [
    '(function () {',
    PAGE_HELPERS,
    '  var typed = ' + typedLit + ';',
    '  var base = logical(typed);',
    '  // Se o usuario digitou um "___N" explicito (ex: nome___1), mira SO aquela',
    '  // linha da tabela pai-filho. Sem sufixo, traz todas as ocorrencias.',
    '  var typedChildMatch = String(typed).match(/___(\\d+)$/);',
    '  var typedChild = typedChildMatch ? typedChildMatch[1] : null;',
    '',
    '  var wins = collectWindows(window, [], 0);',
    '  var matches = [];',
    '',
    '  for (var i = 0; i < wins.length; i++) {',
    '    var w = wins[i];',
    '    var doc;',
    '    try { doc = w.document; } catch (e) { continue; }',
    '    var jq = null;',
    '    try { jq = w.jQuery || w.$ || null; } catch (e) {}',
    '    var nodes;',
    '    try { nodes = doc.querySelectorAll("input, select, textarea, span[name]"); } catch (e) { continue; }',
    '',
    '    for (var j = 0; j < nodes.length; j++) {',
    '      var node = nodes[j];',
    '      var nm = node.getAttribute("name");',
    '      var id = node.id || null;',
    '      var raw = nm || id;',
    '      if (!raw) { continue; }',
    '      if (logical(raw) !== base) { continue; }',
    '',
    '      var childMatch = String(raw).match(/___(\\d+)$/);',
    '      var rawChild = childMatch ? childMatch[1] : null;',
    '      // Filtro por linha: se pediu ___N, so casa a mesma linha.',
    '      if (typedChild !== null && rawChild !== typedChild) { continue; }',
    '',
    '      var v = readValue(node, jq);',
    '      if (v == null) { v = ""; }',
    '',
    '      var table = null;',
    '      try { var t = node.closest ? node.closest("table[tablename]") : null; if (t) { table = t.getAttribute("tablename"); } } catch (e) {}',
    '      var disabled = /^_/.test(String(nm || "")) || /^_/.test(String(id || ""));',
    '      var visible = isNodeVisible(node, w);',
    '      matches.push({',
    '        name: raw,',
    '        id: id,',
    '        value: String(v),',
    '        disabled: disabled,',
    '        visible: visible,',
    '        child: rawChild,',
    '        table: table,',
    '        type: String(node.type || node.tagName || "").toLowerCase(),',
    '        frame: (w === window ? "top" : "iframe"),',
    '        nodeIndex: j,',
    '        exact: (String(raw) === typed)',
    '      });',
    '    }',
    '  }',
    '',
    '  return { typed: typed, base: base, matches: matches, framesScanned: wins.length };',
    '})()'
  ].join('\n');
}

// Rola a pagina do Fluig ate o elemento e aplica um destaque pulsante de 2s.
// Se o elemento estiver oculto (display:none, hidden etc), retorna { ok: false, visible: false }.
function buildFocusElementExpr(rawName) {
  var nameLit = JSON.stringify(String(rawName));
  return [
    '(function () {',
    PAGE_HELPERS,
    '  var targetName = ' + nameLit + ';',
    '  var base = logical(targetName);',
    '  var childMatch = String(targetName).match(/___(\\d+)$/);',
    '  var wantChild = childMatch ? childMatch[1] : null;',
    '  var wins = collectWindows(window, [], 0);',
    '',
    '  for (var i = 0; i < wins.length; i++) {',
    '    var w = wins[i];',
    '    var doc;',
    '    try { doc = w.document; } catch (e) { continue; }',
    '    var nodes;',
    '    try { nodes = doc.querySelectorAll("input, select, textarea, span[name]"); } catch (e) { continue; }',
    '    for (var j = 0; j < nodes.length; j++) {',
    '      var node = nodes[j];',
    '      var nm = node.getAttribute("name");',
    '      var id = node.id || null;',
    '      var raw = nm || id;',
    '      if (!raw) { continue; }',
    '      if (raw !== targetName && logical(raw) !== base) { continue; }',
    '      if (wantChild !== null) {',
    '        var c = String(raw).match(/___(\\d+)$/);',
    '        if (!c || c[1] !== wantChild) { continue; }',
    '      }',
    '',
    '      var jq = null;',
    '      try { jq = w.jQuery || w.$ || null; } catch (e) {}',
    '      uncollapseAncestors(node, jq, w);',
    '',
    '      var visible = isNodeVisible(node, w);',
    '      if (!visible) {',
    '        return { ok: false, visible: false, reason: "Elemento oculto no layout (hidden ou display:none)." };',
    '      }',
    '',
    '      try {',
    '        // Funcao interna para forcar scroll tanto no elemento quanto no frame/janela pai',
    '        function doScroll() {',
    '          try {',
    '            node.scrollIntoView({ behavior: "smooth", block: "center", inline: "center" });',
    '            if (typeof node.focus === "function") { try { node.focus({ preventScroll: true }); } catch (e) {} }',
    '            // Se o elemento esta dentro de um iframe, rola o proprio iframe na janela pai tambem',
    '            if (w !== window && w.frameElement) {',
    '              try {',
    '                w.frameElement.scrollIntoView({ behavior: "smooth", block: "nearest", inline: "nearest" });',
    '              } catch (e) {}',
    '            }',
    '          } catch (e) {}',
    '        }',
    '',
    '        // Passada imediata',
    '        doScroll();',
    '        // Passada secundaria apos o layout do navegador computar as novas dimensoes do painel aberto',
    '        setTimeout(doScroll, 80);',
    '        setTimeout(doScroll, 250);',
    '',
    '        // Aplica borda/halo de destaque temporario',
    '        var prevOutline = node.style.outline;',
    '        var prevBoxShadow = node.style.boxShadow;',
    '        var prevTransition = node.style.transition;',
    '        node.style.transition = "outline 200ms ease, box-shadow 200ms ease";',
    '        node.style.outline = "3px solid #016a71";',
    '        node.style.boxShadow = "0 0 12px rgba(1, 106, 113, 0.6)";',
    '        setTimeout(function () {',
    '          try {',
    '            node.style.outline = prevOutline;',
    '            node.style.boxShadow = prevBoxShadow;',
    '            node.style.transition = prevTransition;',
    '          } catch (e) {}',
    '        }, 2200);',
    '        return { ok: true, visible: true, frame: (w === window ? "top" : "iframe") };',
    '      } catch (e) {',
    '        return { ok: false, visible: true, reason: "Erro ao rolar: " + String(e) };',
    '      }',
    '    }',
    '  }',
    '  return { ok: false, visible: false, reason: "Elemento não encontrado no DOM." };',
    '})()'
  ].join('\n');
}

// Coleta a LINHA inteira de uma tabela pai-filho: todos os campos que estao na
// MESMA tabela (tablename) e no MESMO indice de linha (___N). O escopo por
// tablename e essencial: duas tabelas pai-filho podem ter a linha ___0, e sem
// isso as linhas de tabelas diferentes se misturariam.
function buildRowExpr(tablename, child) {
  return [
    '(function () {',
    PAGE_HELPERS,
    '  var wantTable = ' + JSON.stringify(String(tablename || '')) + ';',
    '  var wantChild = ' + JSON.stringify(String(child)) + ';',
    '',
    '  var wins = collectWindows(window, [], 0);',
    '  var logicalTable = {};',
    '  var rawCandidates = [];',
    '',
    '  for (var i = 0; i < wins.length; i++) {',
    '    var w = wins[i];',
    '    var doc;',
    '    try { doc = w.document; } catch (e) { continue; }',
    '    var jq = null;',
    '    try { jq = w.jQuery || w.$ || null; } catch (e) {}',
    '    var nodes;',
    '    try { nodes = doc.querySelectorAll("input, select, textarea, span[name]"); } catch (e) { continue; }',
    '',
    '    for (var j = 0; j < nodes.length; j++) {',
    '      var node = nodes[j];',
    '      var nm = node.getAttribute("name");',
    '      var id = node.id || null;',
    '      var raw = nm || id;',
    '      if (!raw) { continue; }',
    '      var ntype = String(node.type || node.tagName || "").toLowerCase();',
    '      if (ntype === "button" || ntype === "submit" || ntype === "reset" || ntype === "image") { continue; }',
    '      var lg = logical(raw);',
    '',
    '      var table = null;',
    '      try {',
    '        var t = node.closest ? (node.closest("table[tablename]") || node.closest("table")) : null;',
    '        if (t) { table = t.getAttribute("tablename") || t.id || null; }',
    '      } catch (e) {}',
    '      if (lg && table && !logicalTable[lg]) { logicalTable[lg] = table; }',
    '',
    '      var childMatch = String(raw).match(/___(\\d+)$/);',
    '      var rawChild = childMatch ? childMatch[1] : null;',
    '      if (rawChild !== wantChild) { continue; }',
    '',
    '      var v = readValue(node, jq);',
    '      if (v == null) { v = ""; }',
    '      var disabled = /^_/.test(String(nm || "")) || /^_/.test(String(id || ""));',
    '      var visible = isNodeVisible(node, w);',
    '      rawCandidates.push({',
    '        name: raw,',
    '        id: id,',
    '        field: lg,',
    '        table: table,',
    '        value: String(v),',
    '        disabled: disabled,',
    '        visible: visible,',
    '        type: ntype,',
    '        frame: (w === window ? "top" : "iframe")',
    '      });',
    '    }',
    '  }',
    '',
    '  var fields = [];',
    '  var byField = {};',
    '  for (var k = 0; k < rawCandidates.length; k++) {',
    '    var c = rawCandidates[k];',
    '    var effTable = c.table || logicalTable[c.field] || "Tabela pai-filho";',
    '    if (wantTable && effTable !== wantTable) { continue; }',
    '    var existing = byField[c.field];',
    '    if (!existing) {',
    '      var item = {',
    '        name: c.name,',
    '        id: c.id,',
    '        field: c.field,',
    '        value: c.value,',
    '        disabled: c.disabled,',
    '        visible: c.visible,',
    '        type: c.type,',
    '        frame: c.frame',
    '      };',
    '      byField[c.field] = item;',
    '      fields.push(item);',
    '    } else {',
    '      if (!existing.value && c.value) { existing.value = c.value; }',
    '      if (c.disabled) { existing.disabled = true; }',
    '      if (c.visible) { existing.visible = true; }',
    '    }',
    '  }',
    '',
    '  return { table: wantTable, child: wantChild, fields: fields };',
    '})()'
  ].join('\n');
}
